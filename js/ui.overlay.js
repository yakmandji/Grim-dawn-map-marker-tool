function renderDungeonOverlays() {
  const inner = document.getElementById('mapInner');
  if (!inner || !window.DUNGEON_OVERLAYS) return;

  const core = window.GDMMCore || {};
  const state = core.state;
  if (!state) return;

  const uiCore = window.UiCore || {};
  const resolveSizeKey = uiCore.resolveSizeKey;

  // on initialise si besoin
  state.dungeonOverlays = [];

  inner.querySelectorAll('.dungeon-wrapper').forEach(e => e.remove());

  // correspondances map -> dossier + clé
  const MAP_INFO = {
    '8948x9133': { folder: 'cairn' },
    '5142x3574': { folder: 'malmouth' },
    '5427x5553': { folder: 'korvan' },
  };

  let key = null;
  if (typeof resolveSizeKey === 'function') {
    key = resolveSizeKey(MAP_INFO);
  } else if (state.mapNatural?.w && state.mapNatural?.h) {
    key = `${state.mapNatural.w}x${state.mapNatural.h}`;
  }

  const currentFolder = key && MAP_INFO[key]
    ? MAP_INFO[key].folder
    : null;

  const overlays = window.DUNGEON_OVERLAYS.filter(o => {
    if (!o.map) return true; // pas de map = affiché partout
    if (!currentFolder) return false;
    return o.map === currentFolder;
  });

  overlays.forEach(d => {
    const wrap = document.createElement('div');
    wrap.className = 'dungeon-wrapper';

    const nw = state.mapNatural.w;
    const nh = state.mapNatural.h;

    const leftPx   = (d.left / 100) * nw;
    const topPx    = (d.top / 100) * nh;
    const widthPx  = (d.width / 100) * nw;
    const heightPx = (d.height / 100) * nh;

    wrap.style.left   = leftPx + 'px';
    wrap.style.top    = topPx + 'px';
    wrap.style.width  = widthPx + 'px';
    wrap.style.height = heightPx + 'px';

    const over = document.createElement('div');
    over.className = 'dungeon';

    const path = `img/overlays/${currentFolder}/${d.img}`;
    over.style.backgroundImage = `url(${path})`;

    wrap.appendChild(over);
    inner.appendChild(wrap);

    // --- Activation uniquement au clic/tap ---
    // --- Distinction CLICK vs DRAG sur les overlays donjon ---
    // Si l'utilisateur drag, on laisse le pan fonctionner et on n'active pas l'overlay.
    wrap.__gdmmDragMoved = false;
    wrap.__gdmmStartX = 0;
    wrap.__gdmmStartY = 0;

    wrap.addEventListener('pointerdown', (e) => {
      // On ne stoppe PAS la propagation : on veut que le viewport puisse pan.
      wrap.__gdmmDragMoved = false;
      wrap.__gdmmStartX = e.clientX;
      wrap.__gdmmStartY = e.clientY;
    });

    wrap.addEventListener('pointermove', (e) => {
      const dx = Math.abs(e.clientX - wrap.__gdmmStartX);
      const dy = Math.abs(e.clientY - wrap.__gdmmStartY);

      // seuil anti micro-mouvements (ajuste si besoin : 4..10)
      if (dx + dy > 6) wrap.__gdmmDragMoved = true;
    });

    wrap.addEventListener('pointerup', () => {
      // ne rien faire ici : on garde le flag pour que le click le voie
    });

    wrap.addEventListener('pointercancel', () => {
      wrap.__gdmmDragMoved = false;
    });

    // --- Activation uniquement au clic/tap (si pas un drag) ---
    wrap.addEventListener('click', (e) => {
      const core = window.GDMMCore || {};
      const coreState = core.state || {};

      // Mode ajout de marqueur / route : on laisse le clic remonter
      if (coreState.tool === 'add' || coreState.tool === 'path') {
        wrap.__gdmmDragMoved = false;
        return;
      }

      // Si c'était un drag => on laisse le pan, donc PAS de preventDefault/stopPropagation
      if (wrap.__gdmmDragMoved) {
        wrap.__gdmmDragMoved = false;
        return;
      }

      // Clic "réel" => comportement donjon
      e.preventDefault();
      e.stopPropagation();

      state.activeDungeonOverlayId = state.activeDungeonOverlayId || null;

      if (state.activeDungeonOverlayId === d.id) {
        if (window.clearDungeonLinks) window.clearDungeonLinks();
        state.activeDungeonOverlayId = null;
      } else {
        if (window.showDungeonLinksForOverlay) window.showDungeonLinksForOverlay(d.id);
        state.activeDungeonOverlayId = d.id;
      }

      wrap.__gdmmDragMoved = false;
    });



    state.dungeonOverlays.push({
      cfg: d,
      el: wrap,
      left: d.left,
      top: d.top,
      width: d.width,
      height: d.height,
    });
  });


}

window.renderDungeonOverlays = renderDungeonOverlays;

