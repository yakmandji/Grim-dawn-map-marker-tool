    // --- API i18n de base ----------------------------------

  function setLang(lang) {
    if (!translations[lang]) lang = 'en';
    localStorage.setItem(LANG_KEY, lang);
    applyLang(lang);
  }

  function getLang() {
    return localStorage.getItem(LANG_KEY) || 'en';
  }

  function applyLang(lang) {
    const dict = translations[lang] || translations.en;

    // texte
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) el.textContent = dict[key];
    });

    // placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) el.setAttribute('placeholder', dict[key]);
    });

    // html (quand la traduction contient des balises)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key]) el.innerHTML = dict[key];
    });

    // title
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) el.setAttribute('title', dict[key]);
    });

    // tooltip
    document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
      const key = el.getAttribute('data-i18n-tooltip');
      if (dict[key]) el.setAttribute('data-tooltip', dict[key]);
    });
  }


  function t(key, params = {}) {
    const lang = getLang();
    const dict = translations[lang] || translations.en;
    let text = dict[key] || key;

    // Interpolation {variable}
    for (const p in params) {
      const reg = new RegExp(`{${p}}`, 'g');
      text = text.replace(reg, params[p]);
    }

    return text;
  }

  // --- Helpers génériques pour les dropdowns custom ---------------------

  function initCustomDropdown({
    nativeId,
    dropdownId,
    itemSelector = '.option-item',
    valueAttr = 'data-value',
    currentButtonSelector = '.select-current',
    currentLabelSelector = '.select-label',
    defaultValue = '',
    getLabel,
    extraSync,
  }) {
    const nativeSelect = document.getElementById(nativeId);
    const dropdown = document.getElementById(dropdownId);
    if (!nativeSelect || !dropdown) return;

    initCustomDropdownForElements({
      nativeSelect,
      dropdown,
      itemSelector,
      valueAttr,
      currentButtonSelector,
      currentLabelSelector,
      defaultValue,
      getLabel,
      extraSync,
    });
  }

  // Variante qui prend directement les éléments (pratique pour la liste des marqueurs)
  function initCustomDropdownForElements({
    nativeSelect,
    dropdown,
    itemSelector = '.option-item',
    valueAttr = 'data-value',
    currentButtonSelector = '.select-current',
    currentLabelSelector = '.select-label',
    defaultValue = '',
    getLabel,
    extraSync,
  }) {
    if (!nativeSelect || !dropdown) return;

    const currentBtn = dropdown.querySelector(currentButtonSelector);
    const currentLabel = currentLabelSelector
      ? dropdown.querySelector(currentLabelSelector)
      : null;
    const items = dropdown.querySelectorAll(itemSelector);
    if (!currentBtn || !items.length) return;

    function syncFromSelect() {
      const value = nativeSelect.value || defaultValue;
      const item = dropdown.querySelector(`${itemSelector}[${valueAttr}="${value}"]`);
      if (!item) return;

      if (currentLabel) {
        const labelText = getLabel
          ? getLabel(item, value)
          : (item.textContent || '').trim();
        currentLabel.textContent = labelText;
      }

      if (typeof extraSync === 'function') {
        extraSync({ currentBtn, item, value });
      }
    }

    // Stocke le sync courant sur le dropdown (sera remplacé à chaque re-init)
    dropdown.__gdmmSyncFromSelect = syncFromSelect;

    // Bind 1 seule fois les listeners "globaux"
    if (!dropdown.__gdmmDropdownBound) {
      dropdown.__gdmmDropdownBound = true;

      // Ouverture / fermeture
      currentBtn.addEventListener('click', (e) => {
        e.stopPropagation();
        dropdown.classList.toggle('open');
      });

      document.addEventListener('click', () => {
        dropdown.classList.remove('open');
      });

      // Sync quand le <select> change (via code ou UI) → appelle toujours la dernière fonction
      nativeSelect.addEventListener('change', () => {
        if (typeof dropdown.__gdmmSyncFromSelect === 'function') {
          dropdown.__gdmmSyncFromSelect();
        }
      });
    }

    // Rebind des items (car le menu HTML est reconstruit à chaque refreshProfilesUI)
    items.forEach(btn => {
      btn.addEventListener('click', () => {
        const value = btn.getAttribute(valueAttr);
        if (!value) return;

        nativeSelect.value = value;
        nativeSelect.dispatchEvent(new Event('change'));

        // la fermeture doit rester ici
        dropdown.classList.remove('open');
      });
    });

    // Sync initial
    syncFromSelect();

  }

